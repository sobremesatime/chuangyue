-- 窗月 · 迁移 0016：用户表新增令牌版本
-- 变更目的：支撑「忘记密码 / 重置密码」——重置意味着账号可能已被他人接管，
--           必须让此前签发的刷新令牌立刻失效，否则改完密码攻击者还能继续续期。
-- 机制：登录 / 刷新签发的令牌里带上当时的 token_version；重置密码时该列 +1，
--       刷新时比对不上即拒绝。存量令牌没有这个声明，反序列化为 0，
--       与存量用户的默认值 0 一致，因此升级不会把所有人踢下线。
-- 说明：docker-entrypoint-initdb.d 只在空数据目录时执行，
--       存量 dev 库需手动执行本文件一次。

-- ----------------------------
-- 升级
-- ----------------------------
ALTER TABLE `user`
  ADD COLUMN `token_version` INT NOT NULL DEFAULT 0 COMMENT '令牌版本：重置密码时 +1，使此前签发的刷新令牌全部失效' AFTER `status`;

